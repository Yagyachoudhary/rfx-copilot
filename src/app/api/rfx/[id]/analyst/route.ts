import { audit, getContext } from "@/lib/context";
import { jsonError } from "@/lib/api";
import { loadRfqBundle } from "@/lib/data";
import { buildAnalysisDb } from "@/lib/analysis-db";
import { runAnalyst, type AnalystEvent } from "@/lib/ai/analyst";
import { buildCsv, buildXlsx, uploadExport } from "@/lib/export";

export const maxDuration = 300;

export async function POST(req: Request, { params }: { params: Promise<{ id: string }> }) {
  try {
    const { id } = await params;
    const ctx = await getContext("api");
    const { question } = await req.json();
    if (!question || !String(question).trim()) return Response.json({ error: "Ask a question" }, { status: 400 });
    const b = await loadRfqBundle(ctx.supabase, id);
    if (!b) return Response.json({ error: "Not found" }, { status: 404 });
    const db = await buildAnalysisDb(b);
    const { data: hist } = await ctx.supabase.from("analyst_messages").select("role, content").eq("rfq_id", id).order("created_at", { ascending: true }).limit(40);
    await ctx.supabase.from("analyst_messages").insert({ org_id: ctx.orgId, rfq_id: id, role: "user", content: String(question), created_by: ctx.user.id });

    const enc = new TextEncoder();
    const artifacts: any[] = [];
    const stream = new ReadableStream({
      async start(controller) {
        const emit = (e: AnalystEvent) => {
          if (e.type === "sql" || e.type === "chart" || e.type === "export") artifacts.push(e);
          controller.enqueue(enc.encode(JSON.stringify(e) + "\n"));
        };
        let answer = "";
        try {
          answer = await runAnalyst({
            bundle: b,
            db,
            history: (hist ?? []) as any,
            question: String(question),
            emit,
            exportFile: async (fileName, format, columns, rows, title) => {
              const buf = format === "csv" ? buildCsv(columns, rows) : await buildXlsx([{ name: (title || "Export").slice(0, 31), columns, rows, note: `${b.rfq.ref_code} — generated by the analyst from current reviewed data. Fictional demo data.` }]);
              const out = await uploadExport(ctx.supabase, ctx.orgId, id, fileName, buf, format === "csv" ? "text/csv" : "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet");
              await audit(ctx, "export.created", { rfqId: id, entityType: "export", entityId: out.path, details: { via: "analyst", file: out.fileName, rows: rows.length } });
              return { url: `/api/exports?path=${encodeURIComponent(out.path)}`, fileName: out.fileName };
            },
          });
        } catch (e: any) {
          answer = `Sorry — the analysis failed: ${e?.message ?? e}`;
          emit({ type: "error", text: answer });
        }
        await ctx.supabase.from("analyst_messages").insert({ org_id: ctx.orgId, rfq_id: id, role: "assistant", content: answer, artifacts, created_by: ctx.user.id });
        await audit(ctx, "analyst.question", { rfqId: id, details: { question: String(question).slice(0, 300), queries: artifacts.filter((a) => a.type === "sql").length } });
        emit({ type: "done" });
        controller.close();
      },
    });
    return new Response(stream, { headers: { "content-type": "application/x-ndjson; charset=utf-8", "cache-control": "no-store" } });
  } catch (e) {
    return jsonError(e);
  }
}

export async function DELETE(_req: Request, { params }: { params: Promise<{ id: string }> }) {
  try {
    const { id } = await params;
    const ctx = await getContext("api");
    await ctx.supabase.from("analyst_messages").delete().eq("rfq_id", id);
    return Response.json({ ok: true });
  } catch (e) {
    return jsonError(e);
  }
}
